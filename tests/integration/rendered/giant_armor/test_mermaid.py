"""The mermaid and mermaid-lint skills of giant-armor as a user receives them.

Neutral skills and bundled references; the provenance notice is stage-1
output, covered by the generator's unit tests.
"""

import json
from pathlib import Path

import pytest

from plugin_maintenance.paths import REPO_ROOT


@pytest.fixture
def skills_root(rendered: Path) -> Path:
    return rendered / "giant-armor" / "skills"


def test_skills_use_neutral_layout(skills_root: Path) -> None:
    assert (skills_root / "mermaid" / "SKILL.md").is_file()
    assert (skills_root / "mermaid-lint" / "SKILL.md").is_file()


def test_skill_avoids_claude_specific_source_packaging(skills_root: Path) -> None:
    skill = (skills_root / "mermaid" / "SKILL.md").read_text(encoding="utf-8")

    for phrase in ["Claude", ".claude/skills"]:
        assert phrase not in skill


def test_mermaid_lint_skill_is_renamed(skills_root: Path) -> None:
    lint_skill = (skills_root / "mermaid-lint" / "SKILL.md").read_text(encoding="utf-8")

    assert "name: mermaid-lint" in lint_skill
    assert "name: lint-mermaid" not in lint_skill


def test_references_and_schema_are_preserved(skills_root: Path) -> None:
    references = sorted((skills_root / "mermaid" / "references").glob("*.md"))
    syntax_references = [
        path for path in references if not path.name.startswith("config-") and path.name != "examples.md"
    ]

    assert len(syntax_references) >= 30
    assert {
        "flowchart.md",
        "sequenceDiagram.md",
        "classDiagram.md",
        "entityRelationshipDiagram.md",
        "gantt.md",
        "stateDiagram.md",
    }.issubset({path.name for path in syntax_references})
    assert (skills_root / "mermaid-lint" / "references" / "linter_output_schema.json").is_file()

    for reference in references:
        first_lines = "\n".join(reference.read_text(encoding="utf-8").splitlines()[:6])
        assert "THIS IS AN AUTOGENERATED FILE" not in first_lines
        assert "DO NOT EDIT" not in first_lines


def test_linter_schema_reports_status_input_and_errors(skills_root: Path) -> None:
    schema = json.loads(
        (skills_root / "mermaid-lint" / "references" / "linter_output_schema.json").read_text(encoding="utf-8")
    )

    assert schema["type"] == "object"
    assert schema["required"] == ["status", "input", "errors"]
    assert sorted(schema["properties"]) == ["errors", "input", "status"]


def test_statechart_routes_diagram_type_through_the_mermaid_skill(skills_root: Path) -> None:
    statechart = (skills_root / "mermaid-statechart" / "SKILL.md").read_text(encoding="utf-8")
    frontmatter, body = statechart.split("---\n", 2)[1:]

    assert '"../mermaid/references/stateDiagram.md"' in frontmatter
    assert (skills_root / "mermaid-statechart" / "../mermaid/references/stateDiagram.md").resolve().is_file()
    assert "../mermaid/SKILL.md" in body


def test_readme_documents_mermaid_skills_without_runtime_lock_in() -> None:
    readme = (REPO_ROOT / "README.md").read_text(encoding="utf-8")
    giant_armor_section = readme.split("### `giant-armor`", 1)[1].split("\n### `", 1)[0]

    assert "| `mermaid` |" in giant_armor_section
    assert "| `mermaid-lint` |" in giant_armor_section
    assert "mermaid-diagrams" not in readme
